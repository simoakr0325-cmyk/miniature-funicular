test('2024 年の 366 日すべてで getKou.js と同じ候になる', () => {
  const d = new Date(2024, 0, 1);
  for (let i = 0; i < 366; i++, d.setDate(d.getDate() + 1)) assert.equal(getKou(new Date(d)).id, EXPECTED[i], d.toDateString());
});

test('戻り値の形は getKou.js と同じで、送り仮名の表示も付く', () => {
  const k = getKou(new Date(2026, 5, 12));
  assert.deepEqual([k.id, k.sekki, k.name, k.stage, k.label], ['26', '芒種', '腐草為蛍', '次候', '芒種・次候「腐草為蛍」']);
  assert.equal(k.kisetu, '芒種・次候「腐草蛍と為る」');
  assert.equal(k.yomi, 'ふそうほたるとなる');
  assert.equal(KOU.length, 72);
  assert.equal(getKou(new Date(2026, 11, 31)).name, '麋角解');
  assert.equal(getKou(new Date(2027, 1, 3)).name, '鶏始乳');
});

test('現場ノートの frontmatter に、更新した日の候（kisetu は送り仮名、kou は漢字）', () => {
  const d = createDoc({ siteName: 'A' });
  d.updatedAt = new Date(2026, 10, 9, 12).toISOString();
  const note = toNote(d);
  assert.match(note, /\nkisetu: "立冬・初候「山茶始めて開く」"\nkou: 山茶始開\n/);
});
