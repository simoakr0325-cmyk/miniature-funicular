// 見本の庭。初めて開いた人が、描き方・図面・3D・見積をすぐ試せるように。
// 20 m × 15 m の敷地に、母屋・駐車場・アプローチ・芝庭・デッキ・植栽・景石・塀。

import { createDoc, createElement } from './model.js';

const rect = (x, y, w, h) => [[x, y], [x + w, y], [x + w, y + h], [x, y + h]];

export function sampleDoc() {
  const d = createDoc({ siteId: 'MIHON', siteName: '見本の庭' });
  const add = (kind, pts, props = {}, extra = {}) => d.elements.push(createElement(kind, pts, { props, ...extra }));
  add('shikichi', rect(0, 0, 20000, 15000));
  add('tatemono', rect(7500, 1500, 9100, 6370), { 名前: '母屋', 高さ: 6200 });
  // 駐車場とアプローチ
  add('hoso', rect(500, 8500, 5500, 6000), { 材料: '土間コンクリート' });
  add('hoso', [[6000, 13200], [9000, 13200], [9600, 8000], [8400, 8000], [8000, 12000], [6000, 12000]], { 材料: '洗い出し' });
  add('hoso', rect(500, 500, 6000, 7500), { 材料: '砂利' });
  // 庭
  add('hoso', rect(9800, 8200, 9700, 6300), { 材料: '芝' });
  add('hoso', rect(10800, 7870, 4500, 1800), { 材料: 'ウッドデッキ', 天端: 400 });
  add('shokusaitai', [[15800, 8200], [19500, 8200], [19500, 14500], [17800, 14500], [17800, 10200], [15800, 10200]], { 内容: '低木・下草' });
  add('shokusaitai', rect(9800, 13600, 7600, 900), { 内容: '低木' });
  add('keiseki', [[14200, 11200], [15000, 10900], [15400, 11500], [14900, 12000], [14100, 11800]], { 石種: '浅間石' });
  add('keiseki', [[13300, 12100], [13800, 12000], [13900, 12500], [13400, 12600]], { 石種: '浅間石' });
  // 塀と縁石
  add('hei', [[0, 15000], [6000, 15000]], { 種類: 'ブロック塀', 高さ: 1000 });
  add('hei', [[9000, 15000], [20000, 15000], [20000, 8000]], { 種類: 'ブロック塀', 高さ: 1200 });
  add('enseki', [[9800, 8200], [9800, 13600]], { 種類: '見切り' });
  // 樹木
  const tree = (x, y, name, h, r) => add('jumoku', [[x, y]], { 樹種: name, 樹高: h }, { r });
  tree(18600, 9300, 'コナラ', 5000, 1500);
  tree(16800, 9000, 'アオダモ', 3800, 900);
  tree(18700, 12600, 'ヤマボウシ', 3500, 1100);
  tree(11200, 12300, 'イロハモミジ', 3200, 1200);
  tree(7000, 10200, 'ソヨゴ', 2800, 700);
  tree(3200, 3000, 'アカマツ', 5500, 1300);
  tree(1800, 6200, 'シラカバ', 4500, 800);
  tree(12600, 14050, 'ドウダンツツジ', 900, 400);
  tree(14400, 14050, 'ドウダンツツジ', 900, 400);
  // 高さ（現況はゆるく北へ上がる）
  for (const [x, y, h] of [[0, 0, 300], [20000, 0, 350], [0, 15000, 0], [20000, 15000, 50], [10000, 7500, 180]]) add('takasa', [[x, y]], { 区分: '現況', 高さ: h });
  add('sunpo', [[0, 15000], [20000, 15000], [0, 15900]]);
  add('moji', [[2200, 11600]], { 文字: '駐車 2台' });
  return d;
}
