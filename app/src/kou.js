export const KOU = ROWS.map(([id, sekki, name, start, okuri, yomi]) => ({ id, sekki, name, start, okuri, yomi }));

const STAGES = ['初候', '次候', '末候'];
const WINTER_END = ['64', '65'];
const NEW_YEAR = ['66', '67', '68', '69', '70', '71', '72'];

// getKou.js と同じ：12/22 以後は 64・65、2/4 より前は 66〜72、ほかは 01〜63 の中で、始まりを過ぎた最後の候。
export function getKou(target = new Date()) {
  const date = target instanceof Date ? target : new Date(target);
  const mmdd = (date.getMonth() + 1) * 100 + date.getDate();
  let pool;
  if (mmdd >= 1222) pool = KOU.filter((k) => WINTER_END.includes(k.id));
  else if (mmdd < 204) pool = KOU.filter((k) => NEW_YEAR.includes(k.id));
  else pool = KOU.filter((k) => !WINTER_END.includes(k.id) && !NEW_YEAR.includes(k.id));
  let current = pool[0];
  for (const k of pool) if (mmdd >= k.start[0] * 100 + k.start[1]) current = k;
  const stage = STAGES[(parseInt(current.id, 10) - 1) % 3];
  return {
    id: current.id,
    sekki: current.sekki,
    name: current.name,
    stage,
    label: `${current.sekki}・${stage}「${current.name}」`, // getKou.js の label（漢字）
    okuri: current.okuri,
    yomi: current.yomi,
    kisetu: `${current.sekki}・${stage}「${current.okuri}」`, // 本文・kisetu ラベル用（送り仮名）
  };
}
